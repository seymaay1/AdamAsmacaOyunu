    private void logDosya(String etiket, String mesaj) {
        try {
            FileWriter fw = new FileWriter("C:/P2OYUN/TXTdosyalar/log.txt", true);
            
            java.util.Date simdi = new java.util.Date();
            java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("dd.MM.yyyy HH:mm:ss");
            String zaman = sdf.format(simdi);
            fw.write("[" + etiket + "] " + zaman + " - " + mesaj + "\n");
            fw.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Hata" + e.getMessage());
        }
    }

