    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        try{
            
            JPasswordField pf = new JPasswordField();
            int sonuc = JOptionPane.showConfirmDialog(this, pf, "Yeni şifrenizi girin:", JOptionPane.OK_CANCEL_OPTION);
        
            if (sonuc != JOptionPane.OK_OPTION) 
                return;
            String yeniSifre = new String(pf.getPassword());
       
            if (yeniSifre.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Şifre boş olamaz!");
                return;
            }
        
            FileWriter fw = new FileWriter("C:/P2OYUN/TXTdosyalar/sifre.txt");
            fw.write(yeniSifre);
            fw.close();
        
            JOptionPane.showMessageDialog(this, "Şifre başarıyla kaydedildi!");
            jPasswordField1.setText("");
            logDosya("YENİ ŞİFRE BELİRLENDİ", "Yeni şifre kaydedildi.");
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Hata: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
         try {
            
            
            BufferedReader br = new BufferedReader(new FileReader("C:/P2OYUN/TXTdosyalar/sifre.txt"));
            String sifre = br.readLine();
            br.close();
        
            String girilenSifre = new String(jPasswordField1.getPassword());
        
            if (girilenSifre.equals(sifre)) {
                JOptionPane.showMessageDialog(this, "Giriş başarılı!");
                logDosya("GİRİŞ BAŞARILI", "Kullanıcı giriş yaptı.");
                
                OyunEkranı oyun = new OyunEkranı();
                oyun.setVisible(true);
                this.dispose();
                
            }else {
                sayac++;
                logDosya("HATALI GİRİŞ", "Hatalı deneme sayısı: " + sayac);
                if (sayac >= 3) {
                    System.exit(0);
                } 
                else {
                    JOptionPane.showMessageDialog(this, "Hatalı şifre! Kalan hak: " + (3 - sayac));
                }
            }
       
        
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Hata: " + e.getMessage());
    }
    }//GEN-LAST:event_jButton1ActionPerformed

